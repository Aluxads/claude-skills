// Brain reports: name records per project, generated index.md and weekly-YYYY-MM-DD.md. Names and accounts only.
import { ENVS } from "./defaults.mjs";
import { nameParts, envSegment } from "./naming.mjs";

export const BADGE = { PROD: "🟥", OPS: "🟧", TEST: "🟩", DEV: "🟦", LOCAL: "⬜" };
const MARK = { FAIL: "⚠️ FAIL", WARN: "△ WARN" };
const DAY = 864e5;
const esc = (v) => String(v ?? "").replace(/\r?\n/g, " ").replace(/\|/g, "\\|");
const isoDate = (s) => ((s || "").match(/^(\d{4}-\d{2}-\d{2})\b/) || [])[1] || "";
const daysTo = (d, today) => Math.round((Date.parse(`${d}T00:00:00Z`) - today) / DAY);
const badged = (r) => (BADGE[r.env] ? `${BADGE[r.env]} ${r.name}` : r.name);
const list = (s) => (s || "").split(/[;,]/).map((x) => x.trim()).filter(Boolean);

// Brain files are shared across projects: an email account shows as first letter plus *** before the @ (brain rule: no owner name).
export function maskAccount(a) {
  const m = /^([^@\s]+)@([^@\s]+)$/.exec(String(a).trim());
  return m ? `${m[1][0]}***@${m[2]}` : a;
}

// One record per name in env files or in a live ledger row: provider, account, env, expires, links.
export function nameRecords(project, ledger, envNames, prefix) {
  const map = ledger.mode === "map";
  const has = (c) => ledger.idx[c] !== undefined;
  const val = (r, c) => (r && has(c) ? r.cells[c] : "").trim();
  const retired = (r) => (map ? /retired|deleted|revoked/i : /^retired$/i).test(val(r, "status"));
  const rows = new Map();
  for (const r of ledger.rows) for (const n of r.names) if (!rows.has(n)) rows.set(n, r);
  const names = new Set([...envNames, ...[...rows].filter(([, r]) => !retired(r)).map(([n]) => n)]);
  return [...names].sort().map((name) => {
    const r = rows.get(name);
    const rowEnv = val(r, "env").toUpperCase();
    const env = ENVS.includes(rowEnv) ? rowEnv : envSegment(name);
    const provider = (val(r, "provider") || nameParts(name, prefix).provider).toLowerCase().replace(/^<.*>$/, "unknown");
    return {
      name, project, env, provider, hasRow: !!r,
      account: r ? maskAccount(val(r, "account") || "unknown") : "no row",
      expires: val(r, "expires"),
      source: val(r, "source"),
      shared_with: list(val(r, "shared_with")),
    };
  });
}

// C8 input: names present in 2+ projects. linked = some row sets source or shared_with.
export function sharedNames(records) {
  const by = new Map();
  for (const r of records) {
    if (!by.has(r.name)) by.set(r.name, []);
    by.get(r.name).push(r);
  }
  const out = [];
  for (const [name, rs] of by) {
    const projects = [...new Set(rs.map((r) => r.project))].sort();
    const linked = rs.some((r) => r.source || r.shared_with.length);
    if (projects.length > 1 || linked) out.push({ name, projects, linked, records: rs });
  }
  return out.sort((a, b) => (a.name < b.name ? -1 : 1));
}

const counts = (F) => ({ fail: F.filter((f) => f.level === "FAIL").length, warn: F.filter((f) => f.level === "WARN").length });

// model: { ts, today, projects: [{ name, status: "ok"|"skipped"|"error", reason, records, F }] }
export function renderIndex(model) {
  const ok = model.projects.filter((p) => p.status === "ok");
  const records = ok.flatMap((p) => p.records);
  const tot = counts(ok.flatMap((p) => p.F));
  const L = [
    "<!-- generated by secret-ledger index, do not edit -->",
    "# Credentials index",
    `generated: ${model.ts}, projects: ${ok.length}, names: ${records.length}, FAIL: ${tot.fail}, WARN: ${tot.warn}`,
    `env: ${ENVS.map((e) => `${BADGE[e]} ${e}`).join(", ")}, no badge = env not set`,
    "",
    "## By provider account",
    "| Provider | Account | Projects | Names | Next expiry |",
    "|---|---|---|---|---|",
  ];
  const acc = new Map();
  for (const r of records) {
    const k = `${r.provider}\u0000${r.account}`;
    if (!acc.has(k)) acc.set(k, { provider: r.provider, account: r.account, projects: new Set(), recs: [] });
    acc.get(k).projects.add(r.project);
    acc.get(k).recs.push(r);
  }
  for (const a of [...acc.values()].sort((x, y) => (`${x.provider} ${x.account}` < `${y.provider} ${y.account}` ? -1 : 1))) {
    const envc = ENVS.map((e) => [e, a.recs.filter((r) => r.env === e).length]).filter(([, n]) => n);
    const names = `${a.recs.length}${envc.length ? ` (${envc.map(([e, n]) => `${BADGE[e]} ${n}`).join(", ")})` : ""}`;
    const next = a.recs.map((r) => isoDate(r.expires)).filter(Boolean).sort()[0] || "none";
    L.push(`| ${esc(a.provider)} | ${esc(a.account)} | ${[...a.projects].sort().join(", ")} | ${names} | ${next} |`);
  }
  L.push("", "## By project", "| Project | Names | FAIL | WARN | Last check |", "|---|---|---|---|---|");
  for (const p of model.projects) {
    if (p.status !== "ok") L.push(`| ${esc(p.name)} | - | - | - | ${p.status}: ${esc(p.reason)} |`);
    else {
      const c = counts(p.F);
      L.push(`| ${esc(p.name)} | ${p.records.length} | ${c.fail} | ${c.warn} | ${model.ts} |`);
    }
  }
  L.push("", "## Shared keys", "| Name | Source | Consumed in |", "|---|---|---|");
  for (const s of sharedNames(records)) {
    const src = s.records.find((r) => r.source)?.source || (s.linked ? s.records.find((r) => r.shared_with.length).project : "unlinked (C8)");
    const used = [...new Set([...s.projects, ...s.records.flatMap((r) => r.shared_with)])].sort();
    L.push(`| ${esc(badged(s.records[0]))} | ${esc(src)} | ${esc(used.join(", "))} |`);
  }
  L.push("", "## Expiring in 60 days", "| Name | Project | Expires |", "|---|---|---|");
  const soon = records.map((r) => ({ r, d: isoDate(r.expires) })).filter(({ d }) => d && daysTo(d, model.today) <= 60);
  for (const { r, d } of soon.sort((a, b) => (a.d < b.d ? -1 : a.d > b.d ? 1 : 0))) L.push(`| ${esc(badged(r))} | ${esc(r.project)} | ${d} |`);
  return L.join("\n") + "\n";
}

export function renderWeekly(model, date) {
  const ok = model.projects.filter((p) => p.status === "ok");
  const tot = counts(ok.flatMap((p) => p.F));
  const L = [
    "<!-- generated by secret-ledger check --all, do not edit -->",
    `# Secret ledger weekly ${date}`,
    `generated: ${model.ts}, projects: ${ok.length}, skipped: ${model.projects.length - ok.length}, FAIL: ${tot.fail}, WARN: ${tot.warn}`,
  ];
  for (const p of model.projects) {
    L.push("", `## ${p.name}`);
    if (p.status !== "ok") {
      L.push(`${p.status}: ${p.reason}`);
      continue;
    }
    const c = counts(p.F);
    L.push(c.fail + c.warn ? `FAIL ${c.fail}, WARN ${c.warn}` : "✓ clean");
    if (!p.F.length) continue;
    const ids = new Map();
    for (const f of p.F) {
      if (!ids.has(f.id)) ids.set(f.id, { FAIL: 0, WARN: 0 });
      ids.get(f.id)[f.level]++;
    }
    L.push("", "| Check | FAIL | WARN |", "|---|---|---|");
    for (const [id, n] of [...ids].sort((a, b) => (a[0] < b[0] ? -1 : 1))) L.push(`| ${id} | ${n.FAIL} | ${n.WARN} |`);
    const fails = p.F.filter((f) => f.level === "FAIL");
    if (fails.length) {
      L.push("", "FAIL lines:");
      for (const f of fails) L.push(`- ${MARK.FAIL} ${f.id} ${f.subject}: ${f.msg}${f.tag ? ` [${f.tag}]` : ""}`);
    }
  }
  return L.join("\n") + "\n";
}
